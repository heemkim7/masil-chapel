cache = {}; out = []
for th, refs in R.items():
    for b, c, a, z in refs:
        if b not in cache:
            try: cache[b] = json.load(open(f'/tmp/krv/{b}.json'))
            except FileNotFoundError:
                import urllib.request, urllib.parse
                cache[b] = json.loads(urllib.request.urlopen('https://raw.githubusercontent.com/yuhwan/Bible-krv/master/' + urllib.parse.quote(b) + '.json').read())
        ch = next(x for x in cache[b]['chapters'] if x['chapter'] == c)
        for v in ch['verses']:
            if a <= v['verse'] <= z: out.append({'th': th, 'b': b, 'c': c, 'v': v['verse'], 't': v['text']})
